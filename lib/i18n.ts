export type TranslationKey = keyof (typeof dict)["bn"];

export function translate(locale: Locale, key: TranslationKey | string): string {
  const table = dict[locale] as Record<string, string>;
  const fallback = dict.en as Record<string, string>;
  return table[key] ?? fallback[key] ?? key;
}

/** Bengali numerals (০-৯) when the UI is in Bengali, plain digits otherwise. */
const BN_DIGITS = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];

export function localizeDigits(value: string, locale: Locale): string {
  if (locale !== "bn") return value;
  return value.replace(/\d/g, (d) => BN_DIGITS[Number(d)]);
}
